"""
Q1: Take two numbers as input from the user. Print their sum, difference,
product, and remainder.
"""
Gen = int(input("Enter a number: "))
Rin = int(input("Enter another number: "))
Sum = Gen+Rin
Sub = Gen - Rin
Dot = Gen * Rin
Rem = Gen % Rin
print(f"The sum is {Sum},The difference is {Sub},The product is {Dot},The remainder is {Rem}")
