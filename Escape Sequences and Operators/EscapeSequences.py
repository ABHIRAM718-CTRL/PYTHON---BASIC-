"""
\n - next line
\t - tabspace i.e., 4 consecutive spaces is called tabspace.
\\ - prints backslash - how many you type, half of them will be printed.
\' - prints single quote
\" - prints double quote
"""

print("MOSFET STANDS FOR\t  - \tMetal Oxide Semiconductor Field Effect Transistor")
print("BJT STANDS FOR \n - Bipolar Junction Transistor")
print("BJT STANDS FOR \\\\\\ - \\\\\\Bipolar Junction Transistor") 
print("BJT STANDS FOR \" - \'Bipolar Junction Transistor")

print("My name is \"Abhiram\"")
